drop table users;
CREATE TABLE USERS (
    user_id int generated by default as identity (start with 1) primary key,
    user_name varchar(32) not null,
    user_password varchar(32) not null,
    created_at timestamp not null,
    active int not null,
    primary key (user_id)
);

